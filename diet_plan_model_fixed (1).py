import os
import pandas as pd

# Load the dataset (the CSV must be in the same folder as this script)
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
file_path = os.path.join(BASE_DIR, 'food_nutrition_dataset__2_.csv')
df = pd.read_csv(file_path)

# Display basic information
print("--- Dataset Summary ---")
print(df.info())

print("\n--- First 5 Rows ---")
print(df.head())

print("\n--- Missing Values ---")
print(df.isnull().sum())

# Charts removed to avoid matplotlib/seaborn dependency.

"""### Machine Learning with Decision Tree Classifier
We will preprocess the nutrition dataset, split it into 80% training and 20% testing sets, and train a Decision Tree model to classify the food items into their respective `category` labels based on their nutritional properties.
"""

from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import classification_report, accuracy_score
from sklearn.preprocessing import LabelEncoder
import pandas as pd
import numpy as np

# Define feature columns (numerical nutrition values) and the target
numerical_features = [
    'calories_kcal', 'protein_g', 'carbs_g', 'fat_g', 'saturated_fat_g',
    'fiber_g', 'sugar_g', 'caffeine_mg', 'serving_size_g_or_ml'
]
target_col = 'category'

# Prepare features and target, handling missing values in feature columns
X_full = df[numerical_features].copy()
for col in X_full.columns:
    X_full[col] = X_full[col].fillna(X_full[col].median())

y_full = df[target_col]

# Identify and filter out classes with only 1 member to allow stratified split
class_counts = y_full.value_counts()
valid_classes = class_counts[class_counts >= 2].index

mask = y_full.isin(valid_classes)
X_filtered = X_full[mask]
y_filtered = y_full[mask]

# Encode target labels into integers
le = LabelEncoder()
y_encoded = le.fit_transform(y_filtered)

# Split data into 80% training and 20% testing
X_train, X_test, y_train, y_test = train_test_split(
    X_filtered, y_encoded, test_size=0.20, random_state=42, stratify=y_encoded
)

# Initialize and train Decision Tree model
clf = DecisionTreeClassifier(max_depth=5, random_state=42)
clf.fit(X_train, y_train)

# Make predictions
y_pred = clf.predict(X_test)

# Evaluate the model
accuracy = accuracy_score(y_test, y_pred)
print(f"Model Accuracy: {accuracy * 100:.2f}%\n")
print("Classification Report:")
print(classification_report(y_test, y_pred, target_names=le.classes_, zero_division=0))

"""### Model Improvement: Random Forest Classifier
We will replace the single Decision Tree with an ensemble **Random Forest Classifier** and apply **StandardScaler** to normalize the numerical input ranges.
"""

from sklearn.ensemble import RandomForestClassifier
from sklearn.preprocessing import StandardScaler

# Standardize the features
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# Initialize and train a Random Forest Classifier
rf_clf = RandomForestClassifier(n_estimators=150, max_depth=10, random_state=42, class_weight='balanced')
rf_clf.fit(X_train_scaled, y_train)

# Make predictions
y_pred_rf = rf_clf.predict(X_test_scaled)

# Evaluate the updated model
accuracy_rf = accuracy_score(y_test, y_pred_rf)
print(f"Improved Model (Random Forest) Accuracy: {accuracy_rf * 100:.2f}%\n")
print("Classification Report:")
print(classification_report(y_test, y_pred_rf, target_names=le.classes_, zero_division=0))

"""### Extreme Gradient Boosting (XGBoost) for Maximum Accuracy
We will now train an **XGBoost Classifier**, which iteratively minimizes classification errors using gradient boosting, to see if we can achieve an even higher prediction accuracy.
"""

from xgboost import XGBClassifier

# Initialize the XGBoost Classifier with tuned hyperparameters
xgb_clf = XGBClassifier(
    n_estimators=200,
    max_depth=6,
    learning_rate=0.1,
    subsample=0.8,
    colsample_bytree=0.8,
    random_state=42,
    eval_metric='mlogloss'
)

# Fit the model on our standardized training data
xgb_clf.fit(X_train_scaled, y_train)

# Make predictions
y_pred_xgb = xgb_clf.predict(X_test_scaled)

# Evaluate the XGBoost model
accuracy_xgb = accuracy_score(y_test, y_pred_xgb)
print(f"XGBoost Classifier Accuracy: {accuracy_xgb * 100:.2f}%\n")
print("Classification Report:")
print(classification_report(y_test, y_pred_xgb, target_names=le.classes_, zero_division=0))

"""### Hyperparameter Tuning on Random Forest using Grid Search
We will now use `GridSearchCV` to explore optimal configurations for `n_estimators`, `max_depth`, and `min_samples_split` in our Random Forest model to achieve peak performance.
"""

from sklearn.model_selection import GridSearchCV

# Define the parameter grid to search
param_grid = {
    'n_estimators': [100, 200, 300],
    'max_depth': [10, 15, None],
    'min_samples_split': [2, 5],
    'class_weight': ['balanced', 'balanced_subsample']
}

# Initialize Grid Search with 3-Fold Cross Validation
grid_search = GridSearchCV(
    estimator=RandomForestClassifier(random_state=42),
    param_grid=param_grid,
    cv=3,
    n_jobs=-1,
    scoring='accuracy'
)

# Fit the grid search on the scaled training data
grid_search.fit(X_train_scaled, y_train)

# Get the best estimator
best_rf = grid_search.best_estimator_

# Make predictions with optimized model
y_pred_opt = best_rf.predict(X_test_scaled)

# Evaluate the fine-tuned model
accuracy_opt = accuracy_score(y_test, y_pred_opt)
print(f"Optimized Random Forest Accuracy: {accuracy_opt * 100:.2f}%")
print(f"Best Parameters: {grid_search.best_params_}\n")
print("Classification Report:")
print(classification_report(y_test, y_pred_opt, target_names=le.classes_, zero_division=0))

"""### Ensembling Models: Voting Classifier
To push the accuracy even further, we will build a **Voting Classifier** that combines the strengths of our Random Forest, an Extra Trees Classifier, and an XGBoost model.
"""

from sklearn.ensemble import VotingClassifier, ExtraTreesClassifier

# Initialize individual models
rf_best = RandomForestClassifier(n_estimators=200, max_depth=15, random_state=42, class_weight='balanced')
et_best = ExtraTreesClassifier(n_estimators=200, max_depth=15, random_state=42, class_weight='balanced')
xgb_best = XGBClassifier(n_estimators=150, max_depth=5, learning_rate=0.1, random_state=42, eval_metric='mlogloss')

# Combine them into a Soft Voting Classifier
voting_clf = VotingClassifier(
    estimators=[
        ('rf', rf_best),
        ('et', et_best),
        ('xgb', xgb_best)
    ],
    voting='soft'
)

# Train the Voting Classifier
voting_clf.fit(X_train_scaled, y_train)

# Predict and evaluate
y_pred_vote = voting_clf.predict(X_test_scaled)
accuracy_vote = accuracy_score(y_test, y_pred_vote)
print(f"Voting Classifier Accuracy: {accuracy_vote * 100:.2f}%\n")
print("Classification Report:")
print(classification_report(y_test, y_pred_vote, target_names=le.classes_, zero_division=0))

"""### Saving the Best Model and Preprocessing Artifacts
We will save the optimized Random Forest model (`best_rf`), the scaler (`scaler`), and the label encoder (`le`) to disk so they can be easily reloaded for future predictions.
"""

import joblib

# Save the model, scaler, and label encoder
joblib.dump(best_rf, os.path.join(BASE_DIR, 'best_random_forest_model.pkl'))
joblib.dump(scaler, os.path.join(BASE_DIR, 'scaler.pkl'))
joblib.dump(le, os.path.join(BASE_DIR, 'label_encoder.pkl'))

print("Artifacts saved successfully:")
print("- best_random_forest_model.pkl (Optimized Random Forest Model)")
print("- scaler.pkl (StandardScaler)")
print("- label_encoder.pkl (LabelEncoder)")